export function getDefaultGeographyFromEnvironment(): GeographyAnchor {
  if (typeof window === 'undefined') return 'india-blr';
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    const lang = navigator.language || '';
    if (tz.toLowerCase().includes('singapore') || lang.toLowerCase().endsWith('-sg')) {
      return 'singapore-sin';
    }
  } catch {
    // ignore
  }
  return 'india-blr';
}
